// Generates CSS custom properties from the Figma snapshot in /figma.
// Only values that exist in Figma are emitted, plus the decided tokens pending Figma registration in
// figma-pending/ (their own block, marked `pending`); aliases stay aliases (var() references) so the
// Primitive → Theme → Semantic → Component chain is preserved.
//
//   node scripts/build-tokens.mjs        → writes src/tokens/*.css and src/tokens/tokens.json
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { ROOT, readAllVariables, readPendingVariables, readTextStyles, readEffectStyles } from './lib/figma-snapshot.mjs';

const OUT = path.join(ROOT, 'src', 'tokens');
const COLLECTION_BY_INITIAL = { P: 'Primitive', T: 'Theme', S: 'Semantic', C: 'Component' };
const HEADER = '/* Generated by scripts/build-tokens.mjs from the Figma snapshot in /figma — do not edit by hand. */\n';

/**
 * Figma variable name → CSS custom property name (same convention as the file's WEB code syntax: "/" → "-").
 * Tailwind-style arbitrary values keep their value but drop the brackets — `border-radius/rounded-[2px]` →
 * `--border-radius-rounded-2px` — so no token name needs CSS escaping (F81). The collision guard below
 * catches a bracketed name that would meet a plain one.
 */
export function cssVarName(name) {
  const plain = name.replace(/\[([^\]\s]+)\]/g, '$1');
  const ident = plain.replace(/[/ ]/g, '-').replace(/[^a-zA-Z0-9_-]/g, (c) => `\\${c}`);
  return `--${ident}`;
}

// Once Figma registers a pending token, its snapshot name collides below — then delete it from figma-pending/.
const variables = [...readAllVariables(), ...readPendingVariables()];
const byKey = new Map(variables.map((v) => [`${v.collection}:${v.name}`, v]));

// Guard against two Figma variables collapsing onto the same CSS name.
const seen = new Map();
for (const v of variables) {
  const css = cssVarName(v.name);
  if (seen.has(css)) throw new Error(`CSS name collision: ${css} (${seen.get(css)} / ${v.collection}:${v.name})`);
  seen.set(css, `${v.collection}:${v.name}`);
}

function unitFor(v) {
  const scopes = v.scopes.split(',');
  if (scopes.includes('FONT_WEIGHT')) return '';
  if (scopes.includes('OPACITY')) return '%';
  if (['CORNER_RADIUS', 'GAP', 'STROKE_FLOAT', 'LINE_HEIGHT', 'LETTER_SPACING'].some((s) => scopes.includes(s))) return 'px';
  if (/^(font\/size|shadows\/scale|pro\/screen-size)\//.test(v.name)) return 'px';
  throw new Error(`No unit rule for ${v.collection}:${v.name} [${v.scopes}]`);
}

// Alias, optionally with an opacity (Figma colour alias with opacity, snapshot "@S:name*40%").
const ALIAS = /^@([PTSC]):(.+?)(?:\*(\d+(?:\.\d+)?)%)?$/;

function aliasTarget(raw) {
  const m = ALIAS.exec(raw);
  if (!m) return null;
  const target = byKey.get(`${COLLECTION_BY_INITIAL[m[1]]}:${m[2]}`);
  if (!target) throw new Error(`Alias target not in snapshot: ${raw}`);
  return target;
}

/** Opacity (0–100) of an alias with opacity, or null. */
const aliasOpacity = (raw) => {
  const m = ALIAS.exec(raw);
  return m && m[3] !== undefined ? Number(m[3]) : null;
};

/** #rrggbb[aa] with its alpha multiplied by `opacity` %. */
function withOpacity(hex, opacity) {
  const a = hex.length === 9 ? parseInt(hex.slice(7, 9), 16) / 255 : 1;
  return hex.slice(0, 7) + Math.round(a * (opacity / 100) * 255).toString(16).padStart(2, '0');
}

function cssValue(v) {
  const target = aliasTarget(v.raw);
  if (target) {
    const opacity = aliasOpacity(v.raw);
    return opacity === null ? `var(${cssVarName(target.name)})` : `color-mix(in srgb, var(${cssVarName(target.name)}) ${opacity}%, transparent)`;
  }
  if (v.raw.startsWith('#')) return v.raw;
  if (v.raw.startsWith('"')) return JSON.stringify(JSON.parse(v.raw));
  return `${Number(v.raw)}${unitFor(v)}`;
}

function resolve(v, depth = 0) {
  if (depth > 10) throw new Error(`Alias loop at ${v.name}`);
  const target = aliasTarget(v.raw);
  if (!target) return cssValue(v);
  const opacity = aliasOpacity(v.raw);
  const value = resolve(target, depth + 1);
  return opacity === null ? value : withOpacity(value, opacity);
}

const typeOf = (v) => (resolve(v).startsWith('#') ? 'color' : v.raw.startsWith('"') ? 'string' : 'number');

function block(selector, entries, comment) {
  // A "*/" inside the note would end the comment early and turn the rest into an invalid selector, dropping the rule.
  if (comment?.includes('*/')) throw new Error(`Comment would close early: ${comment}`);
  return `${comment ? `/* ${comment} */\n` : ''}${selector} {\n${entries.map(([k, val]) => `  ${k}: ${val};`).join('\n')}\n}\n`;
}

const files = {};
const json = { source: { fileKey: 'Ry3WecA6sP6lKPop1vXrTp', file: '[Platform] Web Design System', exported: '2026-10-16', synced: '2026-10-19', pending: 'figma-pending/primitive.txt' }, variables: [], textStyles: [], effectStyles: [] };

// Component variables are split per component group: colors/<group>/… → components/<group>.css
// (colors/button_text/* stays with button). Variables without a group path (Figma's root-level
// "default", "hover", … — docs/figma-issues.md B1) are not emitted: their names would be global.
const componentGroup = (name) => {
  const g = name.split('/')[1];
  return g === 'button_text' ? 'button' : g;
};
json.skipped = variables.filter((v) => v.collection === 'Component' && !v.name.includes('/')).map((v) => ({ collection: v.collection, name: v.name, reason: 'no group path (global name)' }));
const outputs = [
  ['Primitive', 'primitive.css', 'Figma collection "Primitive" (Mode 1)', (v) => !v.pending],
  ['Theme', 'theme.css', 'Figma collection "Theme" (Mode 1)', () => true],
  ['Semantic', 'semantic.css', 'Figma collection "Semantic" (Mode 1)', () => true],
];
const groups = [...new Set(variables.filter((v) => v.collection === 'Component' && v.name.includes('/')).map((v) => componentGroup(v.name)))].sort();
for (const g of groups) {
  outputs.push(['Component', `components/${g}.css`, `Figma collection "Component" (Mode 1) — ${g === 'button' ? 'colors/button/*, colors/button_text/*' : `<kind>/${g}/…`}`, (v) => v.name.includes('/') && componentGroup(v.name) === g]);
}
const pushJson = (collection, list, file, extra) => {
  for (const v of list) {
    const target = aliasTarget(v.raw);
    json.variables.push({ collection, name: v.name, cssVar: cssVarName(v.name), type: typeOf(v), scopes: v.scopes, value: cssValue(v), aliasOf: target ? `${target.collection}:${target.name}` : undefined, resolved: resolve(v), file, ...extra });
  }
};
for (const [collection, file, note, pick] of outputs) {
  const list = variables.filter((v) => v.collection === collection && pick(v));
  files[file] = HEADER + block(':root', list.map((v) => [cssVarName(v.name), cssValue(v)]), `${note} — ${list.length} variables`);
  pushJson(collection, list, file);
}
const pending = variables.filter((v) => v.pending);
if (pending.length) {
  const note = `Pending Figma registration (figma-pending/primitive.txt): decided tokens not in Figma yet — ${pending.length} variables`;
  files['primitive.css'] += '\n' + block(':root', pending.map((v) => [cssVarName(v.name), cssValue(v)]), note);
  pushJson('Primitive', pending, 'primitive.css', { pending: 'not in Figma yet (figma-pending/primitive.txt)' });
}

// Text styles → one set of custom properties per style (+ an opt-in utility class).
const WEIGHT_BY_STYLE = { Regular: 400, Medium: 500, SemiBold: 600, Bold: 700, ExtraBold: 800 };
const round = (n) => +Number(n).toFixed(3);
const boundVar = (b) => (b && !b.external ? `var(${cssVarName(b.name)})` : null);
function literalLength(value, unitPercentMeans) {
  if (value.endsWith('px')) return `${round(parseFloat(value))}px`;
  if (value.endsWith('%')) return unitPercentMeans === 'em' ? `${round(parseFloat(value) / 100)}em` : `${round(parseFloat(value))}%`;
  throw new Error(`Unknown length ${value}`);
}
const typographyVars = [];
const typographyClasses = [];
for (const s of readTextStyles()) {
  const slug = s.name.replace(/\//g, '-');
  const b = s.boundVariables;
  const props = {
    'font-family': boundVar(b.fontFamily) ?? JSON.stringify(s.family),
    'font-size': boundVar(b.fontSize) ?? `${s.fontSize}px`,
    'font-weight': boundVar(b.fontWeight) ?? String(WEIGHT_BY_STYLE[s.style]),
    'line-height': boundVar(b.lineHeight) ?? (s.lineHeight === 'AUTO' ? 'normal' : literalLength(s.lineHeight, 'percent')),
    // Figma "%" letter spacing is a percentage of the font size → em.
    'letter-spacing': boundVar(b.letterSpacing) ?? literalLength(s.letterSpacing, 'em'),
    'text-decoration': s.decoration === 'UNDERLINE' ? 'underline' : 'none',
  };
  if (!WEIGHT_BY_STYLE[s.style]) throw new Error(`Unknown font style ${s.style}`);
  for (const [prop, val] of Object.entries(props)) typographyVars.push([`--typography-${slug}-${prop}`, val]);
  typographyClasses.push(block(`.ds-typography-${slug}`, Object.keys(props).map((prop) => [prop, `var(--typography-${slug}-${prop})`])));
  json.textStyles.push({ name: s.name, font: `${s.family} ${s.style}`, cssVarPrefix: `--typography-${slug}-`, className: `ds-typography-${slug}`, props });
}
files['typography.css'] = HEADER + block(':root', typographyVars, `Figma local text styles — ${json.textStyles.length} styles`) + '\n' + typographyClasses.join('\n');

// Effect styles → box-shadow values.
const effectVars = [];
for (const s of readEffectStyles()) {
  const value = s.effects.filter((e) => e.visible).map((e) => {
    if (e.type !== 'DROP_SHADOW' && e.type !== 'INNER_SHADOW') throw new Error(`Unsupported effect ${e.type}`);
    return `${e.type === 'INNER_SHADOW' ? 'inset ' : ''}${e.x}px ${e.y}px ${e.blur}px ${e.spread}px ${e.color}`;
  }).join(', ');
  effectVars.push([`--effect-${s.name}`, value]);
  json.effectStyles.push({ name: s.name, cssVar: `--effect-${s.name}`, value });
}
files['effects.css'] = HEADER + block(':root', effectVars, `Figma local effect styles — ${effectVars.length} styles`);

const tokenFiles = ['primitive.css', 'theme.css', 'semantic.css', 'typography.css', 'effects.css', ...groups.map((g) => `components/${g}.css`)];
files['index.css'] = HEADER + tokenFiles.map((f) => `@import './${f}';`).join('\n') + '\n';

mkdirSync(path.join(OUT, 'components'), { recursive: true });
for (const [file, content] of Object.entries(files)) writeFileSync(path.join(OUT, file), content);
writeFileSync(path.join(OUT, 'tokens.json'), JSON.stringify(json, null, 2) + '\n');
console.log(`tokens: ${json.variables.length} variables, ${json.textStyles.length} text styles, ${json.effectStyles.length} effect styles → src/tokens/`);
